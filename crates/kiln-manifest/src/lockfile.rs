//! Cargo.lock reading and writing: v3 and v4 formats.
//!
//! The lockfile is the contract between machines. Kiln reads cargo's and
//! writes cargo's, byte-for-byte in structure, so a kiln-resolved lockfile is
//! a lockfile cargo accepts and vice versa.

use std::fmt::Write as _;
use std::path::Path;

use kiln_core::{Error, Result};
use semver::Version;

/// A parsed Cargo.lock.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lockfile {
    /// The lock's format version (3 or 4).
    pub version: u32,
    /// Every locked package.
    pub packages: Vec<LockPackage>,
}

/// One `[[package]]` row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockPackage {
    /// The crate name.
    pub name: String,
    /// The exact version.
    pub version: Version,
    /// The source: `registry+https://...` or none for path packages.
    pub source: Option<String>,
    /// The sha256 checksum, hex.
    pub checksum: Option<String>,
    /// Dependencies by name (optionally with their own version pins in v4).
    pub dependencies: Vec<LockDep>,
}

/// A dependency line inside a package row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockDep {
    /// The dependency's name (its `package` name, not any rename).
    pub name: String,
    /// The pinned version, when the line carries one (v4 style).
    pub version: Option<Version>,
}

impl Lockfile {
    /// Parse a Cargo.lock.
    pub fn parse(text: &str) -> Result<Self> {
        let table: toml::Table =
            toml::from_str(text).map_err(|e| Error::parse("Cargo.lock", e))?;
        let version = table
            .get("version")
            .and_then(|v| v.as_integer())
            .and_then(|v| u32::try_from(v).ok())
            .ok_or_else(|| Error::parse("Cargo.lock", "version field is required"))?;
        if version < 3 {
            return Err(Error::unsupported(format!(
                "Cargo.lock version {version}: kiln reads v3 and v4 lockfiles; re-run cargo to upgrade"
            )));
        }
        let mut packages = Vec::new();
        for entry in table.get("package").and_then(|v| v.as_array()).unwrap_or(&Vec::new()) {
            let entry = entry.as_table().ok_or_else(|| {
                Error::parse("Cargo.lock", "every [[package]] must be a table")
            })?;
            let name = entry
                .get("name")
                .and_then(|v| v.as_str())
                .ok_or_else(|| Error::parse("Cargo.lock", "package.name is required"))?
                .to_owned();
            let version = entry
                .get("version")
                .and_then(|v| v.as_str())
                .ok_or_else(|| Error::parse("Cargo.lock", "package.version is required"))?
                .parse()
                .map_err(|e| Error::parse(format!("Cargo.lock package {name} version"), e))?;
            let source = entry.get("source").and_then(|v| v.as_str()).map(str::to_owned);
            let checksum = entry.get("checksum").and_then(|v| v.as_str()).map(str::to_owned);
            let mut dependencies = Vec::new();
            if let Some(deps) = entry.get("dependencies").and_then(|v| v.as_array()) {
                for dep in deps {
                    let line = dep.as_str().ok_or_else(|| {
                        Error::parse("Cargo.lock", "every dependency must be a string")
                    })?;
                    dependencies.push(parse_dep_line(line)?);
                }
            }
            packages.push(LockPackage { name, version, source, checksum, dependencies });
        }
        Ok(Lockfile { version, packages })
    }

    /// Read the lockfile at `path`, if it exists.
    pub fn read(path: &Path) -> Result<Option<Self>> {
        match std::fs::read_to_string(path) {
            Ok(text) => Ok(Some(Self::parse(&text)?)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(Error::io("read", path, e)),
        }
    }

    /// Serialise in Cargo.lock v4 format.
    pub fn to_string_v4(&self) -> String {
        let mut out = String::new();
        out.push_str("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n");
        let mut packages = self.packages.clone();
        packages.sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));
        for pkg in &packages {
            let _ = writeln!(out, "[[package]]");
            let _ = writeln!(out, "name = {:?}", pkg.name);
            let _ = writeln!(out, "version = {:?}", pkg.version.to_string());
            if let Some(source) = &pkg.source {
                let _ = writeln!(out, "source = {source:?}");
            }
            if let Some(checksum) = &pkg.checksum {
                let _ = writeln!(out, "checksum = {checksum:?}");
            }
            let mut deps = pkg.dependencies.clone();
            deps.sort_by(|a, b| a.name.cmp(&b.name));
            if !deps.is_empty() {
                out.push_str("dependencies = [\n");
                for dep in &deps {
                    match &dep.version {
                        Some(v) => out.push_str(&format!(" {} {:?},\n", dep.name, v.to_string())),
                        None => out.push_str(&format!(" {:?},\n", dep.name)),
                    }
                }
                out.push_str("]\n");
            }
            out.push('\n');
        }
        out
    }

    /// Write to `path` atomically (temp file, then rename).
    pub fn write(&self, path: &Path) -> Result<()> {
        let tmp = path.with_extension("lock.tmp");
        std::fs::write(&tmp, self.to_string_v4()).map_err(|e| Error::io("write", &tmp, e))?;
        std::fs::rename(&tmp, path).map_err(|e| Error::io("rename", path, e))?;
        Ok(())
    }

    /// Find a locked package by name.
    pub fn find(&self, name: &str) -> Option<&LockPackage> {
        self.packages.iter().find(|p| p.name == name)
    }
}

/// Parse one dependency line: `name`, `name version`, or `name ? version`
/// (the v3 marker for an alternative registry).
fn parse_dep_line(line: &str) -> Result<LockDep> {
    let line = line.trim();
    if let Some((name, rest)) = line.split_once(' ') {
        // v4 style: `name ? version (source)` or `name version`; the version
        // is the first token of the remainder.
        let rest = rest.trim_start_matches('?').trim();
        if let Some(first) = rest.split_whitespace().next() {
            let version = first
                .parse()
                .map_err(|e| Error::parse(format!("Cargo.lock dependency `{line}`"), e))?;
            return Ok(LockDep { name: name.to_owned(), version: Some(version) });
        }
        return Ok(LockDep { name: name.to_owned(), version: None });
    }
    Ok(LockDep { name: line.to_owned(), version: None })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE_V3: &str = r#"
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "688f82534fbfad9d07f9ab1c88a5e977e94be6a4b69f01e69b0e9c0f98c48a7c0"
dependencies = [
 "serde_derive",
]

[[package]]
name = "serde_derive"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "24de443c3c1b1d8a28e6b1dfb0c1e0e9c0a5b1d2b1b2e0d0e0e0e0e0e0e0e0e0"
"#;

    #[test]
    fn v3_locks_parse_with_checkums_and_deps() {
        let lock = Lockfile::parse(SAMPLE_V3).unwrap();
        assert_eq!(lock.version, 3);
        assert_eq!(lock.packages.len(), 3);
        let serde = lock.find("serde").unwrap();
        assert_eq!(serde.version.to_string(), "1.0.210");
        assert!(serde.source.as_deref().unwrap().starts_with("registry+"));
        assert_eq!(serde.dependencies.len(), 1);
        assert_eq!(serde.dependencies[0].name, "serde_derive");
        let app = lock.find("app").unwrap();
        assert!(app.source.is_none());
    }

    #[test]
    fn round_trip_through_v4() {
        let lock = Lockfile::parse(SAMPLE_V3).unwrap();
        let text = lock.to_string_v4();
        assert!(text.contains("version = 4"));
        let reparsed = Lockfile::parse(&text).unwrap();
        assert_eq!(reparsed.find("serde").unwrap().checksum, lock.find("serde").unwrap().checksum);
        assert_eq!(reparsed.packages.len(), lock.packages.len());
    }

    #[test]
    fn v4_dependency_lines_carry_versions() {
        let dep = parse_dep_line("serde 1.0.210").unwrap();
        assert_eq!(dep.name, "serde");
        assert_eq!(dep.version.unwrap().to_string(), "1.0.210");
        let dep = parse_dep_line("serde ? 1.0.210 (registry+https://x)").unwrap();
        assert_eq!(dep.version.unwrap().to_string(), "1.0.210");
        let dep = parse_dep_line("serde").unwrap();
        assert!(dep.version.is_none());
    }

    #[test]
    fn ancient_locks_are_refused() {
        let err = Lockfile::parse("version = 2\n").unwrap_err();
        assert!(err.to_string().contains("v3 and v4"), "{err}");
    }
}
